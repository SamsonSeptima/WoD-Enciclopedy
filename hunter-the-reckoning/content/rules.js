<p>Развитие связано не только с очками. Работа над Амбицией в конце сеанса восстанавливает один пункт аггравированной Воли. Исполнение Желания — один раз за сеанс — возвращает один пункт потраченной или повреждённой поверхностной Воли. Это делает личные цели не украшением листа, а механизмом выживания.</p>
